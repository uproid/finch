import 'dart:io';
import 'dart:math';
import 'package:finch/finch_app.dart';
import 'package:finch/finch_route.dart';
import 'package:finch/finch_tools.dart';
import '../route/web_route.dart';

/// Example of a file upload. The request size is limited by the framework
/// (`FinchConfigs.maxBodySize`): a bigger request is rejected with
/// `413 Payload Too Large` before this controller runs.
class UploadController extends Controller {
  UploadController();

  /// Where the files are stored. Not inside the public directory, so an
  /// uploaded file can never be requested (and executed) directly.
  Directory get uploadDir => Directory(pathTo('uploads'));

  // Stored names look like `1700000000000-a1b2c3-report.pdf`.
  static final _storedName =
      RegExp(r'^\d+-[a-z0-9]{6}-[a-z0-9_-]{1,40}\.[a-z0-9]{1,5}$');

  @override
  Future<String> index() => exampleUpload();

  /// File name without any directory part (client paths use `/` or `\`).
  String _baseName(String path) => path.split(RegExp(r'[\\/]')).last;

  Future<String> exampleUpload() async {
    return _render();
  }

  Future<String> exampleUploadPost() async {
    // The bytes are in `getFile` and the original name (user controlled,
    // never trust it) in `<field>_filename`.
    final bytes = rq.getFile('file') as List<int>?;
    final originalName = _baseName(rq.get<String>('file_filename', def: ''));
    if (bytes == null || originalName.isEmpty) {
      return _render(error: 'upload.errors.required');
    }

    // Store with a generated name: only `[a-z0-9_-]` survives from the
    // original name, so it can not contain `../` or any path separator.
    final storedName = _makeStoredName(originalName);
    await uploadDir.create(recursive: true);
    await File(joinPaths([uploadDir.path, storedName])).writeAsBytes(bytes);

    return _render(
      result: {
        // User controlled and printed without auto-escape: escape it.
        'originalName': rq.safe(originalName),
        'storedName': storedName,
        'size': ConvertSize.toLogicSizeString(bytes.length),
      },
    );
  }

  Future<String> exampleUploadDelete() async {
    // Only names generated by this controller are accepted, so a request
    // like `name=../../app.dart` can never reach another file.
    final name = rq.get<String>('name', def: '');
    final file = File(joinPaths([uploadDir.path, name]));
    if (_storedName.hasMatch(name) && file.existsSync()) {
      await file.delete();
      return _render(deleted: name);
    }

    return _render(error: 'upload.errors.notFound');
  }

  Future<String> _render({
    String? error,
    String? deleted,
    Map<String, String>? result,
  }) async {
    rq.addParams({
      'uploadError': error,
      'uploadDeleted': deleted,
      'uploadResult': result,
      'uploadFiles': await _listFiles(),
      'uploadMaxBodySizeText': ConvertSize.toLogicSizeString(
        FinchApp.config.maxBodySize,
      ),
    });

    return homeController.renderTemplate('example/upload');
  }

  Future<List<Map<String, Object>>> _listFiles() async {
    if (!uploadDir.existsSync()) {
      return [];
    }

    final files = uploadDir
        .listSync()
        .whereType<File>()
        .where((f) => _storedName.hasMatch(_baseName(f.path)))
        .toList()
      ..sort((a, b) => b.lastModifiedSync().compareTo(a.lastModifiedSync()));

    return files.take(20).map((f) {
      return <String, Object>{
        'name': _baseName(f.path),
        'size': ConvertSize.toLogicSizeString(f.lengthSync()),
        'modified': f.lastModifiedSync().toString().substring(0, 19),
      };
    }).toList();
  }

  String _makeStoredName(String originalName) {
    final dot = originalName.lastIndexOf('.');
    final base = (dot > 0 ? originalName.substring(0, dot) : originalName)
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9_-]+'), '-')
        .replaceAll(RegExp(r'^-+|-+$'), '');
    final safeBase = base.isEmpty ? 'file' : base;
    var extension = dot > 0
        ? originalName
            .substring(dot + 1)
            .toLowerCase()
            .replaceAll(RegExp(r'[^a-z0-9]'), '')
        : '';
    if (extension.isEmpty || extension.length > 5) {
      extension = 'bin';
    }

    final random = Random.secure();
    final suffix = List.generate(
      6,
      (_) => 'abcdefghijklmnopqrstuvwxyz0123456789'[random.nextInt(36)],
    ).join();

    return '${DateTime.now().millisecondsSinceEpoch}-$suffix-'
        '${safeBase.length > 40 ? safeBase.substring(0, 40) : safeBase}'
        '.$extension';
  }
}
